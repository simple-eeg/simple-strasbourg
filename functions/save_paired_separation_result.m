function separation_result = save_paired_separation_result(final_path, separation_result, source_files)
%SAVE_PAIRED_SEPARATION_RESULT Add source hashes and atomically save one result.

final_path = char(string(final_path));
if isempty(final_path) || ~endsWith(final_path, '.mat')
    error('save_paired_separation_result:InvalidPath', 'final_path must name a .mat file.');
end
if ~isstruct(separation_result) || ~isscalar(separation_result)
    error('save_paired_separation_result:InvalidResult', ...
        'separation_result must be a scalar struct.');
end
required = {'schema','pairing_table','pair_differences','estimate','settings','counts','environment'};
for idx = 1:numel(required)
    if ~isfield(separation_result, required{idx})
        error('save_paired_separation_result:MissingResultField', ...
            'separation_result.%s is required.', required{idx});
    end
end
if ~strcmp(separation_result.schema, 'simple-paired-separation-result-v2')
    error('save_paired_separation_result:UnknownSchema', ...
        'Unsupported separation-result schema: %s', string(separation_result.schema));
end
required_pair_columns = {'reference_value','true_value','true_minus_reference'};
required_effect_columns = {'Estimate','ConfidenceIntervals'};
if ~istable(separation_result.pairing_table) || ...
        ~all(ismember(required_pair_columns, ...
        separation_result.pairing_table.Properties.VariableNames)) || ...
        ~all(varfun(@isnumeric, separation_result.pairing_table(:, required_pair_columns), ...
        'OutputFormat', 'uniform')) || ...
        ~isnumeric(separation_result.pair_differences) || ...
        ~isreal(separation_result.pair_differences) || ...
        ~isvector(separation_result.pair_differences) || ...
        any(~isfinite(separation_result.pair_differences(:))) || ...
        numel(separation_result.pair_differences) ~= height(separation_result.pairing_table) || ...
        ~istable(separation_result.estimate) || height(separation_result.estimate) ~= 1 || ...
        ~all(ismember(required_effect_columns, ...
        separation_result.estimate.Properties.VariableNames)) || ...
        ~isnumeric(separation_result.estimate.Estimate) || ...
        ~isreal(separation_result.estimate.Estimate) || ...
        ~isscalar(separation_result.estimate.Estimate) || ...
        ~isfinite(separation_result.estimate.Estimate) || ...
        ~isnumeric(separation_result.estimate.ConfidenceIntervals) || ...
        ~isreal(separation_result.estimate.ConfidenceIntervals) || ...
        numel(separation_result.estimate.ConfidenceIntervals) ~= 2 || ...
        any(~isfinite(separation_result.estimate.ConfidenceIntervals(:))) || ...
        separation_result.estimate.ConfidenceIntervals(2) < ...
        separation_result.estimate.ConfidenceIntervals(1)
    error('save_paired_separation_result:InvalidTables', ...
        'The paired-difference vector, pairing table, and one-row estimate table are invalid.');
end
pair_differences = double(separation_result.pair_differences(:));
table_differences = double(separation_result.pairing_table.true_minus_reference(:));
calculated_differences = double(separation_result.pairing_table.true_value(:)) - ...
    double(separation_result.pairing_table.reference_value(:));
if ~isequaln(pair_differences, table_differences) || ...
        ~isequaln(pair_differences, calculated_differences)
    error('save_paired_separation_result:DifferenceMismatch', ...
        'pair_differences must equal true_value - reference_value in pairing-table order.');
end
required_settings = {'estimator','statistic','estimand','direction', ...
    'effect_specification','paired','difference_definition', ...
    'bootstrap_resampling_unit','confidence_interval','alpha','rng', ...
    'estimator_implementation','participant_aggregation'};
if ~isstruct(separation_result.settings) || ~isscalar(separation_result.settings) || ...
        ~all(isfield(separation_result.settings, required_settings))
    error('save_paired_separation_result:InvalidEstimator', ...
        'The paired-estimator settings are incomplete.');
end
estimator = string(separation_result.settings.estimator);
if ~isscalar(estimator) || ismissing(estimator) || ...
        ~ismember(estimator, ["pairedmediandiff","pairedmeandiff"])
    error('save_paired_separation_result:InvalidEstimator', ...
        'settings.estimator must be pairedmediandiff or pairedmeandiff.');
end
if estimator == "pairedmediandiff"
    expected_statistic = "median";
    expected_estimand = "Median of within-pair differences";
    expected_row_name = "PairedMedianDifference";
    expected_estimate = median(pair_differences);
else
    expected_statistic = "mean";
    expected_estimand = "Mean of within-pair differences";
    expected_row_name = "PairedMeanDifference";
    expected_estimate = mean(pair_differences);
end
if ~isequal(string(separation_result.settings.statistic), expected_statistic) || ...
        ~isequal(string(separation_result.settings.estimand), expected_estimand) || ...
        ~isequal(string(separation_result.settings.direction), ...
        "true event minus internal reference within each complete pair") || ...
        ~isstruct(separation_result.settings.effect_specification) || ...
        ~isscalar(separation_result.settings.effect_specification) || ...
        ~isfield(separation_result.settings.effect_specification, 'effect') || ...
        ~isequal(string(separation_result.settings.effect_specification.effect), estimator) || ...
        ~isequal(string(separation_result.estimate.Properties.RowNames), expected_row_name) || ...
        ~isequaln(double(separation_result.estimate.Estimate), expected_estimate) || ...
        ~(islogical(separation_result.settings.paired) && ...
        isscalar(separation_result.settings.paired) && separation_result.settings.paired) || ...
        ~isequal(string(separation_result.settings.difference_definition), ...
        "true_value - reference_value within each complete pair") || ...
        ~isequal(string(separation_result.settings.bootstrap_resampling_unit), ...
        "complete pair represented by one difference score") || ...
        ~isequal(string(separation_result.settings.confidence_interval), ...
        "bias-corrected and accelerated (BCa)") || ...
        ~isequal(string(separation_result.settings.estimator_implementation), ...
        "MATLAB bootci applied once to pair_differences") || ...
        ~isequal(string(separation_result.settings.participant_aggregation), "none")
    error('save_paired_separation_result:InconsistentEstimator', ...
        'The estimate, paired-difference vector, row label, or estimator metadata are inconsistent.');
end
rng_settings = separation_result.settings.rng;
required_rng = {'seed','generator','generating_state','bootstrap_resamples', ...
    'bootstrap_interval','bootstrap_function','resampling_unit', ...
    'difference_definition','statistic'};
if ~isstruct(rng_settings) || ~isscalar(rng_settings) || ...
        ~all(isfield(rng_settings, required_rng)) || ...
        ~isequal(string(rng_settings.bootstrap_interval), ...
        "bias-corrected and accelerated (BCa)") || ...
        ~isequal(string(rng_settings.bootstrap_function), "MATLAB bootci") || ...
        ~isequal(string(rng_settings.resampling_unit), ...
        "complete pair represented by one true-minus-reference difference score") || ...
        ~isequal(string(rng_settings.statistic), expected_statistic) || ...
        ~(isnumeric(rng_settings.bootstrap_resamples) && ...
        isscalar(rng_settings.bootstrap_resamples) && ...
        isfinite(rng_settings.bootstrap_resamples) && ...
        rng_settings.bootstrap_resamples > 0) || ...
        ~(isnumeric(separation_result.settings.alpha) && ...
        isscalar(separation_result.settings.alpha) && ...
        isfinite(separation_result.settings.alpha) && ...
        separation_result.settings.alpha > 0 && ...
        separation_result.settings.alpha < 1)
    error('save_paired_separation_result:InvalidBootstrapProvenance', ...
        'The paired BCa bootstrap metadata are incomplete or inconsistent.');
end
if ~isstruct(source_files) || ~isscalar(source_files) || isempty(fieldnames(source_files))
    error('save_paired_separation_result:InvalidSources', ...
        'source_files must be a non-empty scalar struct of named local files.');
end

source_names = string(fieldnames(source_files));
n_sources = numel(source_names);
source_paths = strings(n_sources, 1);
source_bytes = zeros(n_sources, 1);
source_sha256 = strings(n_sources, 1);
for idx = 1:n_sources
    source_paths(idx) = string(source_files.(source_names(idx)));
    if ~isscalar(source_paths(idx)) || ismissing(source_paths(idx)) || ~isfile(source_paths(idx))
        error('save_paired_separation_result:MissingSource', ...
            'Required source file is missing: %s', source_paths(idx));
    end
    info = dir(source_paths(idx));
    source_bytes(idx) = info.bytes;
    source_sha256(idx) = string(sha256_file(source_paths(idx)));
end
separation_result.provenance = table(source_names, source_paths, source_bytes, source_sha256, ...
    'VariableNames', {'name','path','bytes','sha256'});

parent_dir = fileparts(final_path);
if ~isfolder(parent_dir)
    [created, message] = mkdir(parent_dir);
    if ~created
        error('save_paired_separation_result:CreateDirectoryFailed', ...
            'Could not create output directory %s: %s', parent_dir, message);
    end
end

partial_path = [final_path, '.partial'];
if isfile(partial_path)
    delete(partial_path);
end
partial_cleanup = onCleanup(@() delete_if_present(partial_path));

save(partial_path, 'separation_result', '-v7.3');
check = load(partial_path, '-mat', 'separation_result');
if ~isfield(check, 'separation_result') || ~isequaln(check.separation_result, separation_result)
    error('save_paired_separation_result:VerificationFailed', ...
        'The temporary result did not round-trip exactly; the final file was not replaced.');
end

[moved, message] = movefile(partial_path, final_path, 'f');
if ~moved
    error('save_paired_separation_result:PromotionFailed', ...
        'Could not promote the complete temporary result: %s', message);
end
end

function delete_if_present(file_path)
if isfile(file_path)
    try %#ok<TRYNC>
        delete(file_path);
    end
end
end

function h = sha256_file(file_path)
fid = fopen(file_path, 'rb');
if fid == -1
    error('save_paired_separation_result:OpenFailed', ...
        'Could not open source file for hashing: %s', file_path);
end
file_cleanup = onCleanup(@() fclose(fid));

digest = java.security.MessageDigest.getInstance('SHA-256');
chunk_size = 1024 * 1024;
while true
    [chunk, count] = fread(fid, chunk_size, '*uint8');
    if count > 0
        signed_chunk = reshape(typecast(chunk(:), 'int8'), 1, []);
        digest.update(signed_chunk);
    end
    if count < chunk_size
        break
    end
end
[read_message, read_errno] = ferror(fid);
normal_eof = (read_errno == -4) && feof(fid);
if read_errno ~= 0 && ~normal_eof
    error('save_paired_separation_result:ReadFailed', ...
        'Failed while hashing %s: %s', file_path, read_message);
end
h = lower(reshape(dec2hex(typecast(digest.digest(), 'uint8'), 2).', 1, []));
end
