function result = load_guardrail_separation_result(resultPath, expected)
%LOAD_GUARDRAIL_SEPARATION_RESULT Load and validate one saved schema-v2 result.
%   result = LOAD_GUARDRAIL_SEPARATION_RESULT(resultPath, expected) returns
%   the unchanged separation_result stored in resultPath. It performs no
%   estimation, bootstrap, RNG operation, plotting, logging, or write.
%
%   expected must contain:
%     channel, reference_event, true_event, metric, nrf_name,
%     use_exclusion_flags, and source_paths. nrf_name is empty for QC.
%   source_paths is a scalar struct containing exact local paths for:
%     input_csv, script, compute_helper, plot_helper, save_helper.

resultPath = text_scalar(resultPath, 'resultPath');
if ~isfile(resultPath)
    error('load_guardrail_separation_result:MissingResult', ...
        'Saved separation result is missing: %s', resultPath);
end
if ~endsWith(lower(resultPath), '.mat')
    error('load_guardrail_separation_result:InvalidPath', ...
        'resultPath must identify a MAT file.');
end

requiredExpected = {'channel','reference_event','true_event','metric', ...
    'nrf_name','use_exclusion_flags','source_paths'};
if ~isstruct(expected) || ~isscalar(expected) || ...
        ~all(isfield(expected, requiredExpected))
    error('load_guardrail_separation_result:InvalidExpected', ...
        'expected is missing one or more required fields.');
end
expectedChannel = text_scalar(expected.channel, 'expected.channel');
expectedReferenceEvent = text_scalar(expected.reference_event, ...
    'expected.reference_event');
expectedTrueEvent = text_scalar(expected.true_event, 'expected.true_event');
expectedMetric = text_scalar(expected.metric, 'expected.metric');
expectedNRFName = optional_text_scalar(expected.nrf_name, 'expected.nrf_name');
if expectedReferenceEvent == expectedTrueEvent
    error('load_guardrail_separation_result:InvalidExpected', ...
        'Expected reference and true events must differ.');
end
if ~islogical(expected.use_exclusion_flags) || ...
        ~isscalar(expected.use_exclusion_flags) || ...
        ~expected.use_exclusion_flags
    error('load_guardrail_separation_result:InvalidExpected', ...
        'The guardrail consumer requires expected.use_exclusion_flags=true.');
end
requiredSourceNames = {'input_csv','script','compute_helper', ...
    'plot_helper','save_helper'};
if ~isstruct(expected.source_paths) || ~isscalar(expected.source_paths) || ...
        ~all(isfield(expected.source_paths, requiredSourceNames)) || ...
        numel(fieldnames(expected.source_paths)) ~= numel(requiredSourceNames)
    error('load_guardrail_separation_result:InvalidExpectedSources', ...
        'expected.source_paths must contain exactly the five required source paths.');
end

contents = whos('-file', char(resultPath));
if numel(contents) ~= 1 || ~strcmp(contents(1).name, 'separation_result')
    error('load_guardrail_separation_result:UnexpectedMATContents', ...
        'The MAT file must contain exactly one variable named separation_result.');
end
loaded = load(char(resultPath), '-mat', 'separation_result');
if ~isfield(loaded, 'separation_result') || ...
        ~isstruct(loaded.separation_result) || ...
        ~isscalar(loaded.separation_result)
    error('load_guardrail_separation_result:InvalidResult', ...
        'separation_result must be one scalar struct.');
end
result = loaded.separation_result;

requiredResultFields = {'schema','role','pairing_table','pair_differences', ...
    'estimate','settings','counts','environment','provenance'};
if ~all(isfield(result, requiredResultFields))
    error('load_guardrail_separation_result:MissingResultField', ...
        'separation_result is missing one or more required fields.');
end
if ~text_equals(result.schema, 'simple-paired-separation-result-v2')
    error('load_guardrail_separation_result:UnknownSchema', ...
        'Unsupported separation-result schema.');
end
if ~text_equals(result.role, 'descriptive, non-exclusionary guardrail')
    error('load_guardrail_separation_result:InvalidRole', ...
        'The saved object does not have the descriptive guardrail role.');
end

[pairCount, pairDifferences] = validate_pairing_table(result, ...
    expectedChannel, expectedReferenceEvent, expectedTrueEvent, expectedNRFName);
validate_estimate_and_settings(result, pairDifferences, expectedChannel, ...
    expectedReferenceEvent, expectedTrueEvent, expectedMetric, ...
    expectedNRFName, expected.use_exclusion_flags);
validate_counts(result.counts, pairCount, strlength(expectedNRFName) > 0);
validate_environment(result.environment);
validate_provenance(result.provenance, expected.source_paths, requiredSourceNames);
end

function [pairCount, differences] = validate_pairing_table(result, ...
        expectedChannel, expectedReferenceEvent, expectedTrueEvent, expectedNRFName)
pairingTable = result.pairing_table;
requiredColumns = {'PairIndex','subjectID','sessionID','runID','channel', ...
    'reference_epoch_index','true_epoch_index','reference_eventtype', ...
    'true_eventtype','reference_value','true_value','true_minus_reference'};
isNRF = strlength(expectedNRFName) > 0;
if isNRF
    requiredColumns{end+1} = 'NRFName';
end
if ~istable(pairingTable) || isempty(pairingTable) || ...
        ~all(ismember(requiredColumns, pairingTable.Properties.VariableNames))
    error('load_guardrail_separation_result:InvalidPairingTable', ...
        'The pairing table is empty or missing required columns.');
end
pairCount = height(pairingTable);

pairIndex = pairingTable.PairIndex;
if ~isnumeric(pairIndex) || ~isreal(pairIndex) || ~isvector(pairIndex) || ...
        any(~isfinite(pairIndex)) || ...
        ~isequal(double(pairIndex(:)), (1:pairCount).')
    error('load_guardrail_separation_result:InvalidPairIndex', ...
        'PairIndex must equal (1:nPairs)'' in pairing-table order.');
end

textColumns = {'subjectID','sessionID','runID','channel', ...
    'reference_epoch_index','true_epoch_index','reference_eventtype', ...
    'true_eventtype'};
if isNRF
    textColumns{end+1} = 'NRFName';
end
normalisedText = struct();
for columnIdx = 1:numel(textColumns)
    columnName = textColumns{columnIdx};
    try
        values = string(pairingTable.(columnName)(:));
    catch
        error('load_guardrail_separation_result:InvalidPairIdentity', ...
            'Pairing column %s must contain text-compatible identities.', columnName);
    end
    values = strtrim(values);
    if numel(values) ~= pairCount || any(ismissing(values)) || ...
            any(strlength(values) == 0)
        error('load_guardrail_separation_result:InvalidPairIdentity', ...
            'Pairing column %s contains a blank or missing identity.', columnName);
    end
    normalisedText.(columnName) = values;
end

if any(~strcmpi(normalisedText.channel, expectedChannel)) || ...
        any(normalisedText.reference_eventtype ~= expectedReferenceEvent) || ...
        any(normalisedText.true_eventtype ~= expectedTrueEvent)
    error('load_guardrail_separation_result:PairRouteMismatch', ...
        'Pairing-table channel or event labels do not match the expected route.');
end
if isNRF && any(normalisedText.NRFName ~= expectedNRFName)
    error('load_guardrail_separation_result:PairNRFMismatch', ...
        'Pairing-table NRFName does not match the expected template.');
end

keyTable = table(normalisedText.subjectID, normalisedText.sessionID, ...
    normalisedText.runID, upper(normalisedText.channel), ...
    'VariableNames', {'subjectID','sessionID','runID','channel'});
[~, uniqueRows] = unique(keyTable, 'rows', 'stable');
if numel(uniqueRows) ~= pairCount
    error('load_guardrail_separation_result:DuplicatePairKey', ...
        'Pairing keys must be unique by subject, session, run, and channel.');
end

numericColumns = {'reference_value','true_value','true_minus_reference'};
for columnIdx = 1:numel(numericColumns)
    values = pairingTable.(numericColumns{columnIdx});
    if ~isnumeric(values) || ~isreal(values) || ~isvector(values) || ...
            numel(values) ~= pairCount || any(~isfinite(values))
        error('load_guardrail_separation_result:InvalidPairValues', ...
            'Pairing column %s must contain one finite real value per pair.', ...
            numericColumns{columnIdx});
    end
end
referenceValues = double(pairingTable.reference_value(:));
trueValues = double(pairingTable.true_value(:));
tableDifferences = double(pairingTable.true_minus_reference(:));
if ~isnumeric(result.pair_differences) || ...
        ~isreal(result.pair_differences) || ...
        ~isvector(result.pair_differences) || ...
        numel(result.pair_differences) ~= pairCount || ...
        any(~isfinite(result.pair_differences))
    error('load_guardrail_separation_result:InvalidDifferences', ...
        'pair_differences must contain one finite real value per pair.');
end
differences = double(result.pair_differences(:));
if ~isequal(differences, tableDifferences) || ...
        ~isequal(differences, trueValues - referenceValues)
    error('load_guardrail_separation_result:DifferenceMismatch', ...
        'Stored differences do not exactly equal true minus reference values.');
end
end

function validate_estimate_and_settings(result, differences, expectedChannel, ...
        expectedReferenceEvent, expectedTrueEvent, expectedMetric, ...
        expectedNRFName, expectedUseExclusions)
estimate = result.estimate;
if ~istable(estimate) || height(estimate) ~= 1 || ...
        ~all(ismember({'Estimate','ConfidenceIntervals'}, ...
        estimate.Properties.VariableNames)) || ...
        ~isnumeric(estimate.Estimate) || ~isreal(estimate.Estimate) || ...
        ~isscalar(estimate.Estimate) || ~isfinite(estimate.Estimate) || ...
        ~isnumeric(estimate.ConfidenceIntervals) || ...
        ~isreal(estimate.ConfidenceIntervals) || ...
        numel(estimate.ConfidenceIntervals) ~= 2 || ...
        any(~isfinite(estimate.ConfidenceIntervals(:)))
    error('load_guardrail_separation_result:InvalidEstimate', ...
        'The saved estimate table is invalid.');
end
confidenceInterval = double(estimate.ConfidenceIntervals(1, :));
if confidenceInterval(2) < confidenceInterval(1)
    error('load_guardrail_separation_result:InvalidInterval', ...
        'The saved confidence interval endpoints are not ordered.');
end
if ~isequal(string(estimate.Properties.RowNames), "PairedMedianDifference") || ...
        ~isequal(double(estimate.Estimate), median(differences))
    error('load_guardrail_separation_result:EstimateMismatch', ...
        'The saved estimate is not the exact median of stored pair differences.');
end

settings = result.settings;
requiredSettings = {'direction','estimand','effect_specification','paired', ...
    'estimator','statistic','difference_definition', ...
    'bootstrap_resampling_unit','confidence_interval', ...
    'estimator_implementation','alpha','rng','channel','true_event', ...
    'reference_event','metric','use_exclusion_flags','pairing_key', ...
    'participant_aggregation'};
if strlength(expectedNRFName) > 0
    requiredSettings{end+1} = 'NRFName';
end
if ~isstruct(settings) || ~isscalar(settings) || ...
        ~all(isfield(settings, requiredSettings))
    error('load_guardrail_separation_result:InvalidSettings', ...
        'Saved settings are missing one or more required fields.');
end

if ~text_equals(settings.estimator, 'pairedmediandiff') || ...
        ~text_equals(settings.statistic, 'median') || ...
        ~text_equals(settings.estimand, 'Median of within-pair differences') || ...
        ~text_equals(settings.direction, ...
        'true event minus internal reference within each complete pair') || ...
        ~text_equals(settings.difference_definition, ...
        'true_value - reference_value within each complete pair') || ...
        ~text_equals(settings.bootstrap_resampling_unit, ...
        'complete pair represented by one difference score') || ...
        ~text_equals(settings.confidence_interval, ...
        'bias-corrected and accelerated (BCa)') || ...
        ~text_equals(settings.estimator_implementation, ...
        'MATLAB bootci applied once to pair_differences') || ...
        ~text_equals(settings.pairing_key, ...
        'subjectID, sessionID, runID, channel') || ...
        ~text_equals(settings.participant_aggregation, 'none')
    error('load_guardrail_separation_result:EstimatorSettingsMismatch', ...
        'Saved paired-median estimator metadata do not match the accepted route.');
end
if ~islogical(settings.paired) || ~isscalar(settings.paired) || ...
        ~settings.paired || ...
        ~islogical(settings.use_exclusion_flags) || ...
        ~isscalar(settings.use_exclusion_flags) || ...
        settings.use_exclusion_flags ~= expectedUseExclusions || ...
        ~isnumeric(settings.alpha) || ~isreal(settings.alpha) || ...
        ~isscalar(settings.alpha) || settings.alpha ~= 0.05
    error('load_guardrail_separation_result:AnalysisSettingsMismatch', ...
        'Saved pairing, exclusion, or alpha settings do not match the accepted route.');
end
if ~text_equals_ci(settings.channel, expectedChannel) || ...
        ~text_equals(settings.reference_event, expectedReferenceEvent) || ...
        ~text_equals(settings.true_event, expectedTrueEvent) || ...
        ~text_equals(settings.metric, expectedMetric)
    error('load_guardrail_separation_result:RouteSettingsMismatch', ...
        'Saved channel, events, or metric do not match the expected route.');
end
if strlength(expectedNRFName) > 0
    if ~text_equals(settings.NRFName, expectedNRFName)
        error('load_guardrail_separation_result:RouteSettingsMismatch', ...
            'Saved NRFName does not match the expected template.');
    end
elseif isfield(settings, 'NRFName')
    error('load_guardrail_separation_result:UnexpectedNRFSetting', ...
        'The QC result unexpectedly contains an NRFName setting.');
end

effect = settings.effect_specification;
requiredEffectFields = {'effect','estimand','statistic','table_row_name', ...
    'direction','axis_label','contrast_tick_label', ...
    'positive_value_interpretation','scale'};
if ~isstruct(effect) || ~isscalar(effect) || ...
        ~all(isfield(effect, requiredEffectFields)) || ...
        ~text_equals(effect.effect, 'pairedmediandiff') || ...
        ~text_equals(effect.estimand, 'Median of within-pair differences') || ...
        ~text_equals(effect.statistic, 'median') || ...
        ~text_equals(effect.table_row_name, 'PairedMedianDifference') || ...
        ~text_equals(effect.direction, ...
        'true event minus internal reference within each complete pair') || ...
        ~text_equals(effect.axis_label, ...
        'Median paired difference (true - reference)') || ...
        ~text_equals(effect.contrast_tick_label, 'Median paired difference') || ...
        ~text_equals(effect.positive_value_interpretation, ...
        ['Positive values indicate a positive median within-pair ', ...
        'true-minus-reference difference.']) || ...
        ~text_equals(effect.scale, 'original metric units')
    error('load_guardrail_separation_result:EffectSpecificationMismatch', ...
        'Saved effect specification does not match pairedmediandiff.');
end

rngSettings = settings.rng;
requiredRngFields = {'seed','generator','generating_state', ...
    'bootstrap_resamples','bootstrap_interval','bootstrap_function', ...
    'resampling_unit','difference_definition','statistic'};
if ~isstruct(rngSettings) || ~isscalar(rngSettings) || ...
        ~all(isfield(rngSettings, requiredRngFields)) || ...
        ~isnumeric(rngSettings.seed) || ~isreal(rngSettings.seed) || ...
        ~isscalar(rngSettings.seed) || rngSettings.seed ~= 1 || ...
        ~text_equals(rngSettings.generator, 'twister') || ...
        ~isnumeric(rngSettings.generating_state) || ...
        isempty(rngSettings.generating_state) || ...
        any(~isfinite(rngSettings.generating_state(:))) || ...
        ~isnumeric(rngSettings.bootstrap_resamples) || ...
        ~isreal(rngSettings.bootstrap_resamples) || ...
        ~isscalar(rngSettings.bootstrap_resamples) || ...
        rngSettings.bootstrap_resamples ~= 100000 || ...
        ~text_equals(rngSettings.bootstrap_interval, ...
        'bias-corrected and accelerated (BCa)') || ...
        ~text_equals(rngSettings.bootstrap_function, 'MATLAB bootci') || ...
        ~text_equals(rngSettings.resampling_unit, ...
        ['complete pair represented by one true-minus-reference ', ...
        'difference score']) || ...
        ~text_equals(rngSettings.difference_definition, ...
        'true_values - reference_values in matched input order') || ...
        ~text_equals(rngSettings.statistic, 'median')
    error('load_guardrail_separation_result:RNGSettingsMismatch', ...
        'Saved BCa/RNG metadata do not match the accepted route.');
end
end

function validate_counts(counts, pairCount, isNRF)
if ~isstruct(counts) || ~isscalar(counts)
    error('load_guardrail_separation_result:InvalidCounts', ...
        'counts must be one scalar struct.');
end
if isNRF
    required = {'rows_after_channel_filter','rows_after_template_filter', ...
        'excluded_rows_all_templates', ...
        'excluded_rows_selected_events_all_templates', ...
        'excluded_rows_selected_template', ...
        'excluded_rows_selected_events_and_template', ...
        'reference_rows_after_filters','true_rows_after_filters', ...
        'groups_in_scope','incomplete_groups_dropped','nan_pairs_dropped', ...
        'pairs_analysed'};
    referenceField = 'reference_rows_after_filters';
    trueField = 'true_rows_after_filters';
else
    required = {'rows_after_channel_filter','excluded_rows_all', ...
        'excluded_rows_selected_events','reference_rows_after_exclusion', ...
        'true_rows_after_exclusion','groups_in_scope', ...
        'incomplete_groups_dropped','nan_pairs_dropped','pairs_analysed'};
    referenceField = 'reference_rows_after_exclusion';
    trueField = 'true_rows_after_exclusion';
end
if ~all(isfield(counts, required)) || numel(fieldnames(counts)) ~= numel(required)
    error('load_guardrail_separation_result:InvalidCounts', ...
        'counts does not contain the exact fields required for this result type.');
end
for fieldIdx = 1:numel(required)
    value = counts.(required{fieldIdx});
    if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
            ~isfinite(value) || value < 0 || mod(value, 1) ~= 0
        error('load_guardrail_separation_result:InvalidCounts', ...
            'counts.%s must be one nonnegative finite integer.', required{fieldIdx});
    end
end
if counts.pairs_analysed ~= pairCount || ...
        counts.groups_in_scope ~= pairCount + ...
        counts.incomplete_groups_dropped + counts.nan_pairs_dropped || ...
        counts.(referenceField) + counts.(trueField) ~= ...
        2 * (pairCount + counts.nan_pairs_dropped) + ...
        counts.incomplete_groups_dropped || ...
        counts.(referenceField) < pairCount || counts.(trueField) < pairCount
    error('load_guardrail_separation_result:CountMismatch', ...
        'Saved pair, group, row, and dropped-group counts are incoherent.');
end
if isNRF
    if counts.excluded_rows_selected_events_and_template > ...
            counts.excluded_rows_selected_template || ...
            counts.excluded_rows_selected_events_and_template > ...
            counts.excluded_rows_selected_events_all_templates || ...
            counts.excluded_rows_selected_template > ...
            counts.excluded_rows_all_templates || ...
            counts.excluded_rows_selected_events_all_templates > ...
            counts.excluded_rows_all_templates || ...
            counts.rows_after_template_filter < ...
            counts.(referenceField) + counts.(trueField) || ...
            counts.rows_after_channel_filter < ...
            counts.rows_after_template_filter + ...
            counts.excluded_rows_selected_template
        error('load_guardrail_separation_result:CountMismatch', ...
            'Saved NRF filter and exclusion counts are incoherent.');
    end
else
    if counts.excluded_rows_selected_events > counts.excluded_rows_all || ...
            counts.rows_after_channel_filter < ...
            counts.(referenceField) + counts.(trueField) + ...
            counts.excluded_rows_selected_events
        error('load_guardrail_separation_result:CountMismatch', ...
            'Saved QC row and exclusion counts are incoherent.');
    end
end
end

function validate_environment(environment)
required = {'matlab_version','matlab_release','computer'};
if ~isstruct(environment) || ~isscalar(environment) || ...
        ~all(isfield(environment, required))
    error('load_guardrail_separation_result:InvalidEnvironment', ...
        'Saved environment metadata are incomplete.');
end
for fieldIdx = 1:numel(required)
    text_scalar(environment.(required{fieldIdx}), ...
        ['environment.', required{fieldIdx}]);
end
end

function validate_provenance(provenance, expectedSources, requiredNames)
requiredColumns = {'name','path','bytes','sha256'};
if ~istable(provenance) || height(provenance) ~= numel(requiredNames) || ...
        ~all(ismember(requiredColumns, provenance.Properties.VariableNames))
    error('load_guardrail_separation_result:InvalidProvenance', ...
        'Provenance must contain exactly five named source rows.');
end
names = strtrim(string(provenance.name(:)));
paths = strtrim(string(provenance.path(:)));
digests = lower(strtrim(string(provenance.sha256(:))));
if any(ismissing(names)) || any(strlength(names) == 0) || ...
        any(ismissing(paths)) || any(strlength(paths) == 0) || ...
        any(ismissing(digests)) || any(strlength(digests) ~= 64) || ...
        numel(unique(names)) ~= numel(names) || ...
        ~isequal(sort(names), sort(string(requiredNames(:)))) || ...
        ~isnumeric(provenance.bytes) || ~isreal(provenance.bytes) || ...
        ~isvector(provenance.bytes) || numel(provenance.bytes) ~= height(provenance) || ...
        any(~isfinite(provenance.bytes)) || any(provenance.bytes < 0) || ...
        any(mod(provenance.bytes, 1) ~= 0)
    error('load_guardrail_separation_result:InvalidProvenance', ...
        'Provenance names, paths, byte counts, or digests are invalid.');
end
for digestIdx = 1:numel(digests)
    if isempty(regexp(char(digests(digestIdx)), '^[0-9a-f]{64}$', 'once'))
        error('load_guardrail_separation_result:InvalidProvenance', ...
            'Provenance SHA-256 values must be 64 lowercase hexadecimal characters.');
    end
end

for sourceIdx = 1:numel(requiredNames)
    sourceName = requiredNames{sourceIdx};
    row = find(names == string(sourceName));
    if numel(row) ~= 1
        error('load_guardrail_separation_result:MissingProvenanceSource', ...
            'Required provenance source %s is absent or duplicated.', sourceName);
    end
    expectedPath = text_scalar(expectedSources.(sourceName), ...
        ['expected.source_paths.', sourceName]);
    if ~isfile(expectedPath)
        error('load_guardrail_separation_result:MissingSource', ...
            'Required current source is missing: %s', expectedPath);
    end
    storedCanonical = canonical_path(paths(row));
    expectedCanonical = canonical_path(expectedPath);
    if ~strcmp(storedCanonical, expectedCanonical)
        error('load_guardrail_separation_result:SourcePathMismatch', ...
            ['Provenance source %s does not bind the expected local file. ', ...
            'Stored %s; expected %s.'], ...
            sourceName, storedCanonical, expectedCanonical);
    end
    sourceInfo = dir(expectedCanonical);
    if numel(sourceInfo) ~= 1 || sourceInfo.bytes ~= provenance.bytes(row)
        error('load_guardrail_separation_result:SourceBytesMismatch', ...
            'Current byte count differs for provenance source %s.', sourceName);
    end
    currentDigest = sha256_file(expectedCanonical);
    if ~strcmp(currentDigest, char(digests(row)))
        error('load_guardrail_separation_result:SourceHashMismatch', ...
            'Current SHA-256 differs for provenance source %s.', sourceName);
    end
end
end

function value = text_scalar(value, label)
value = string(value);
if ~isscalar(value) || ismissing(value) || strlength(strtrim(value)) == 0
    error('load_guardrail_separation_result:InvalidText', ...
        '%s must be one nonblank text scalar.', label);
end
value = strtrim(value);
end

function value = optional_text_scalar(value, label)
value = string(value);
if ~isscalar(value) || ismissing(value)
    error('load_guardrail_separation_result:InvalidText', ...
        '%s must be one text scalar (empty is allowed).', label);
end
value = strtrim(value);
end

function tf = text_equals(actual, expected)
actual = string(actual);
expected = string(expected);
tf = isscalar(actual) && ~ismissing(actual) && ...
    isscalar(expected) && ~ismissing(expected) && ...
    strtrim(actual) == strtrim(expected);
end

function tf = text_equals_ci(actual, expected)
actual = string(actual);
expected = string(expected);
tf = isscalar(actual) && ~ismissing(actual) && ...
    isscalar(expected) && ~ismissing(expected) && ...
    strcmpi(strtrim(actual), strtrim(expected));
end

function value = canonical_path(value)
value = char(java.io.File(char(string(value))).getCanonicalPath());
end

function digestText = sha256_file(filePath)
fid = fopen(filePath, 'rb');
if fid == -1
    error('load_guardrail_separation_result:SourceOpenFailed', ...
        'Could not open source file for hashing: %s', filePath);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
digest = java.security.MessageDigest.getInstance('SHA-256');
chunkSize = 1024 * 1024;
while true
    [chunk, count] = fread(fid, chunkSize, '*uint8');
    if count > 0
        signedChunk = reshape(typecast(chunk(:), 'int8'), 1, []);
        digest.update(signedChunk);
    end
    if count < chunkSize
        break;
    end
end
[readMessage, readErrno] = ferror(fid);
normalEof = readErrno == -4 && feof(fid);
if readErrno ~= 0 && ~normalEof
    error('load_guardrail_separation_result:SourceReadFailed', ...
        'Failed while hashing %s: %s', filePath, readMessage);
end
digestText = lower(reshape(dec2hex(typecast(digest.digest(), 'uint8'), 2).', 1, []));
end
